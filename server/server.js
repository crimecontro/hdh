// PC Guard relay: serves the phone page and relays WebSocket messages between a phone and the PC agent.
// It never sees your PIN, and screen frames pass through it encrypted (end-to-end).
const http = require('http');
const fs = require('fs');
const path = require('path');
const { WebSocketServer } = require('ws');

const PORT = process.env.PORT || 8080;
const rooms = new Map(); // roomId -> { agent: ws|null, phones: Set<ws> }

const FILES = {
  '/': ['phone.html', 'text/html; charset=utf-8', 'no-store'],
  '/icon.svg': ['icon.svg', 'image/svg+xml', 'public, max-age=86400'],
  '/manifest.webmanifest': ['manifest.webmanifest', 'application/manifest+json', 'public, max-age=86400'],
};
const CSP = "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; " +
  "img-src 'self' data: blob:; connect-src 'self' ws: wss:; manifest-src 'self'; base-uri 'none'; " +
  "form-action 'none'; frame-ancestors 'none'";

const server = http.createServer((req, res) => {
  const f = FILES[req.url.split('?')[0]];
  if (!f) { res.writeHead(404); return res.end('Not found'); }
  res.writeHead(200, {
    'Content-Type': f[1],
    'Cache-Control': f[2],
    'Content-Security-Policy': CSP,
    'X-Content-Type-Options': 'nosniff',
    'Referrer-Policy': 'no-referrer',
  });
  fs.createReadStream(path.join(__dirname, f[0])).pipe(res);
});

const wss = new WebSocketServer({ server, maxPayload: 4 * 1024 * 1024 });

function sendJson(ws, obj) {
  if (ws && ws.readyState === 1) ws.send(JSON.stringify(obj));
}

wss.on('connection', (ws, req) => {
  const url = new URL(req.url, 'http://x');
  const role = url.searchParams.get('role');
  const room = url.searchParams.get('room') || '';

  // room id must be a 32-char hex secret generated by the agent
  if (!/^[a-f0-9]{32}$/.test(room) || !['agent', 'phone'].includes(role)) return ws.close();

  let r = rooms.get(room);
  if (!r) { r = { agent: null, phones: new Set() }; rooms.set(room, r); }

  if (role === 'agent') {
    if (r.agent && r.agent !== ws) r.agent.close();
    r.agent = ws;
    r.phones.forEach((p) => sendJson(p, { type: 'agent_status', online: true }));
  } else {
    r.phones.add(ws);
    sendJson(ws, { type: 'agent_status', online: !!r.agent });
  }

  // phones: max 120 messages per second (mouse moves etc). The agent is not limited (it sends frames).
  let count = 0;
  const timer = setInterval(() => { count = 0; }, 1000);

  ws.isAlive = true;
  ws.on('pong', () => { ws.isAlive = true; });

  ws.on('message', (data, isBinary) => {
    if (role === 'phone') {
      if (isBinary || data.length > 4096 || ++count > 120) return;
      if (r.agent && r.agent.readyState === 1) r.agent.send(data.toString());
      else sendJson(ws, { type: 'agent_status', online: false });
    } else {
      r.phones.forEach((p) => {
        if (p.readyState !== 1) return;
        if (isBinary && p.bufferedAmount > 1048576) return; // slow phone: drop frame instead of buffering
        p.send(data, { binary: isBinary });
      });
    }
  });

  ws.on('close', () => {
    clearInterval(timer);
    if (role === 'agent' && r.agent === ws) {
      r.agent = null;
      r.phones.forEach((p) => sendJson(p, { type: 'agent_status', online: false }));
    } else {
      r.phones.delete(ws);
    }
    if (!r.agent && r.phones.size === 0) rooms.delete(room);
  });
});

// drop dead connections
setInterval(() => {
  wss.clients.forEach((ws) => {
    if (!ws.isAlive) return ws.terminate();
    ws.isAlive = false;
    ws.ping();
  });
}, 25000);

server.listen(PORT, () => console.log('Relay listening on port ' + PORT));
